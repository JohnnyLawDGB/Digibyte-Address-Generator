#!/bin/sh
# Runs after the root filesystem is assembled, before it is packed.
# Arguments after the target dir: the consoles that get the HoldFast session.
set -eu
TARGET_DIR=$1
shift

# No services, no getty, no login: init starts the session menu and nothing else.
{
	echo '# HoldFast Vault: generated by os/board/holdfast/post-build.sh'
	echo '::sysinit:/bin/mount -t proc proc /proc'
	echo '::sysinit:/bin/mkdir -p /dev/pts /dev/shm'
	echo '::sysinit:/bin/mount -a'
	echo '::sysinit:/bin/hostname -F /etc/hostname'
	for console in "$@"; do
		echo "${console}::respawn:/usr/bin/holdfast-session"
	done
	echo '::ctrlaltdel:/sbin/poweroff -f'
	echo '::shutdown:/bin/umount -a -r'
} > "${TARGET_DIR}/etc/inittab"

# Nothing loadable ships in the image: every driver the device needs is built
# into the kernel, and there is no module on disk for any network hardware.
rm -rf "${TARGET_DIR}/lib/modules" "${TARGET_DIR}/usr/lib/modules"

# Init scripts, network config and remote-access leftovers are not used.
rm -rf "${TARGET_DIR}/etc/init.d" "${TARGET_DIR}/etc/network" "${TARGET_DIR}/etc/ssh"

# Root has no usable password and no shell entry point.
if [ -f "${TARGET_DIR}/etc/shadow" ]; then
	sed -i 's|^root:[^:]*:|root:*:|' "${TARGET_DIR}/etc/shadow"
fi
